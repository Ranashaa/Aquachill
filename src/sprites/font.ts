interface Glyph {
  w: number;
  rows: string[];
}

function parse(table: Record<string, string>): Record<string, Glyph> {
  return Object.fromEntries(
    Object.entries(table).map(([ch, g]) => {
      const rows = g.split(' ');
      return [ch, { w: Math.max(...rows.map((r) => r.length)), rows }];
    }),
  );
}

const FONTS: Record<FontId, { h: number; glyphs: Record<string, Glyph> }> = {
  big: { h: 7, glyphs: parse(BIG) },
  small: { h: 5, glyphs: parse(SMALL) },
};

export function fontHeight(font: FontId = 'big'): number {
  return FONTS[font].h;
}

export function normalizeText(text: string): string {
  return text.normalize('NFD').replace(/[̀-ͯ]/g, '').toUpperCase();
}

function glyph(font: FontId, ch: string): Glyph {
  const g = FONTS[font].glyphs;
  return g[ch] ?? g['?'];
}

export function measureText(text: string, font: FontId = 'big'): number {
  let w = 0;
  for (const ch of normalizeText(text)) w += glyph(font, ch).w + 1;
  return Math.max(0, w - 1);
}

export function drawText(
  ctx: CanvasRenderingContext2D,
  text: string,
  x: number,
  y: number,
  color: string,
  font: FontId = 'big',
): void {
  ctx.fillStyle = color;
  let cx = x;
  for (const ch of normalizeText(text)) {
    const g = glyph(font, ch);
    g.rows.forEach((row, ry) => {
      for (let rx = 0; rx < row.length; rx++) if (row[rx] === '#') ctx.fillRect(cx + rx, y + ry, 1, 1);
    });
    cx += g.w + 1;
  }
}
